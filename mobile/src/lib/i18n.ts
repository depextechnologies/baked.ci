const en: Record<Key, string> = { ...enBase, ...enC };

export type Lang = 'fr' | 'en';
export type TKey = Key;
const dicts: Record<Lang, Record<Key, string>> = { fr, en };

export const translate = (lang: Lang, key: Key, vars?: Record<string, string | number>) => {
  let s = dicts[lang][key] ?? fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
};

export const statusLabel = (lang: Lang, status?: string) => {
  const key = `status.${status}` as Key;
  return key in fr ? translate(lang, key) : (status || '').replace(/_/g, ' ');
};
